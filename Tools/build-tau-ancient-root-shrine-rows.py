#!/usr/bin/env python3
"""Taurus V4 phase 06 GREYBOX: rows + flat-colour ground for the Ancient Root Shrine (96 x 64), one linear dungeon in 3 rooms.

  python Tools/build-tau-ancient-root-shrine-rows.py            # rows -> TauAncientRootShrineMap.cs, ground / border PNGs, layout preview, checks
  python Tools/build-tau-ancient-root-shrine-rows.py --check    # only the checks, writes nothing

Layout (BIBLE part2 I.2: Area 01 24x22, Area 02 28x24, Area 03 30x28, corridors 3-5 wide), entrance south-west, the boss far north:
  Area 01 Tangled Root Passage (x 2-25, y 38-59)  --corridor A (4 wide)-->  Area 02 Amber Memory Hall (x 30-57, y 36-59)
  --corridor B (4 wide, east, the checkpoint crystal in its north wall)-->  antechamber of 3 Rune Bark Guardians (x 67-82, y 33-49)
  --gate neck (y 30-32)-->  Area 03 Heartroot Sanctuary, a 30 x 28 ellipse (centre 75.5, 15.5): the hero comes in from the south, the Elder Root Guardian waits in the north.
96 x 64 = GameConfig.MaxTilesW x MaxTilesH (a taller map would need the engine limits raised).
Row chars: T solid rock / wall   p root passage   a amber hall   s sanctuary   c corridor / antechamber (all walkable, only the colour differs; palette = part2 I.1).
GREYBOX: flat colours, no props; the environment art comes separately.
"""
import math, os, re, sys
from collections import deque
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPS = os.path.join(ROOT, "Assets", "Scripts", "Maps")
TILES = os.path.join(ROOT, "Assets", "Resources", "Sprites", "village", "tiles")
SHOTS = os.path.join(ROOT, "docs", "reference", "world-design", "greybox-shots")
W, H, PX = 96, 64, 16
COL = {"T": (0x48, 0x57, 0x44), "p": (0x80, 0x67, 0x47), "a": (0x90, 0x8B, 0x77), "s": (0x7A, 0x84, 0x62), "c": (0x6E, 0x5A, 0x40)}
SOLID = "T"

# rooms: (x0, x1, y0, y1) inclusive
AREA1, AREA2 = (2, 25, 38, 59), (30, 57, 36, 59)
CORR_A, CORR_B = (26, 29, 46, 49), (58, 66, 46, 49)
ANTE, NECK = (67, 82, 33, 49), (74, 77, 30, 32)
ARENA_C, ARENA_R = (75.5, 15.5), (15.4, 14.4)            # ellipse centre (x, y) and radii: 30 x 28
MOUTH = (5, 8, 33, 37)                                    # entrance stub, 4 wide; the exit portals are its first row
START = (6, 39)                                           # where a hero arrives (6 rows below the portal row)
CRYSTAL_GATE = (2, 41, 3, 41)                             # warp crystal 1: solid tile in the west wall of the entrance room (tile x, y, arrival x, y)
CRYSTAL_DEEP = (62, 45, 62, 46)                           # warp crystal 2: solid tile in the north wall of corridor B
AMBER = (43, 47, 44, 48)                                  # Memory Amber: solid 2 x 2 block in the middle of Area 02 (x0, y0, x1, y1)
BOSS = (75, 10)


def rect(g, x0, x1, y0, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): g[y][x] = c


def build():
    g = [["T"] * W for _ in range(H)]
    for r, c in ((AREA1, "p"), (AREA2, "a"), (CORR_A, "c"), (CORR_B, "c"), (ANTE, "c"), (NECK, "c")): rect(g, r[0], r[1], r[2], r[3], c)
    for y in range(H):
        for x in range(W):
            if ((x + 0.5 - ARENA_C[0]) / ARENA_R[0]) ** 2 + ((y + 0.5 - ARENA_C[1]) / ARENA_R[1]) ** 2 <= 1.0: g[y][x] = "s"
    # corners of the two big rooms cut round so they read as caves, not boxes
    for (x0, x1, y0, y1) in (AREA1, AREA2):
        for cx, cy in ((x0, y0), (x1, y0), (x0, y1), (x1, y1)):
            sx, sy = (1 if cx == x0 else -1), (1 if cy == y0 else -1)
            for dx, dy in ((0, 0), (1, 0), (0, 1)): g[cy + sy * dy][cx + sx * dx] = "T"
    rect(g, MOUTH[0], MOUTH[1], MOUTH[2], AREA1[2] + 1, "p")                    # the entrance stub opens into Area 01
    g[CRYSTAL_GATE[1]][CRYSTAL_GATE[0]] = "T"; g[CRYSTAL_DEEP[1]][CRYSTAL_DEEP[0]] = "T"
    rect(g, AMBER[0], AMBER[2], AMBER[1], AMBER[3], "T")
    return ["".join(r) for r in g]


def patch(path, rows):
    s = open(path, encoding="utf-8").read()
    a, b = s.index("// BEGIN ROWS"), s.index("// END ROWS")
    body = "// BEGIN ROWS (generated by Tools/build-tau-ancient-root-shrine-rows.py)\n        static readonly string[] Rows =\n        {\n" + "".join('            "%s",\n' % r for r in rows) + "        };\n        "
    open(path, "w", encoding="utf-8", newline="\n").write(s[:a] + body + s[b:])


def camps():
    s = open(os.path.join(ROOT, "Assets", "Scripts", "MapSpawnTable.cs"), encoding="utf-8").read()
    a = s.index("TauAncientRootShrine =")
    blk = s[a:s.index("};", a)]
    rx = r'new FrostHollowMap\.Zone\("(\w+)", (\d+), (\d+), (\d+), (\d+), (\d+), \d+f\)'
    return [(m[0], int(m[1]), int(m[2]), int(m[3]), int(m[4]), int(m[5])) for m in re.findall(rx, blk)]


def flood(rows, start):
    seen = {start}; q = deque([start])
    while q:
        x, y = q.popleft()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and rows[ny][nx] not in SOLID: seen.add((nx, ny)); q.append((nx, ny))
    return seen


def span(rows, x, y, horizontal):
    """Open run through (x, y) along one axis (a corridor's width is the run ACROSS it)."""
    n = 1
    for d in (1, -1):
        k = 1
        while True:
            cx, cy = (x + d * k, y) if horizontal else (x, y + d * k)
            if rows[cy][cx] in SOLID: break
            n += 1; k += 1
    return n


def check(rows):
    bad = []
    free = {(x, y) for y in range(H) for x in range(W) if rows[y][x] not in SOLID}
    reach = flood(rows, START)
    for t in sorted(free - reach)[:5]: bad.append("walkable tile not reachable from the start: %s" % (t,))
    if any(c not in SOLID for y in (H - 3, H - 2, H - 1) for c in rows[y]): bad.append("bottom rows are not blocked (under the HUD)")
    if rows[START[1]][START[0]] in SOLID: bad.append("start is solid")
    if rows[BOSS[1]][BOSS[0]] in SOLID: bad.append("boss tile is solid")
    for nm, (tx, ty, ax, ay) in (("crystal gate", CRYSTAL_GATE), ("crystal deep", CRYSTAL_DEEP)):
        if rows[ty][tx] not in SOLID or rows[ay][ax] in SOLID: bad.append(nm + ": needs a solid tile with a free arrival beside it")
    if any(rows[y][x] not in SOLID for x in range(AMBER[0], AMBER[2] + 1) for y in range(AMBER[1], AMBER[3] + 1)): bad.append("memory amber block is not solid")
    for nm, w in (("corridor A", span(rows, 27, 47, False)), ("corridor B", span(rows, 62, 47, False)), ("neck", span(rows, 75, 31, True)), ("mouth", span(rows, 6, 35, True))):
        if not 3 <= w <= 5: bad.append("%s is %d wide, BIBLE says 3-5" % (nm, w))
    arena = [(x, y) for y in range(H) for x in range(W) if rows[y][x] == "s"]
    if max(p[0] for p in arena) - min(p[0] for p in arena) + 1 < 30 or max(p[1] for p in arena) - min(p[1] for p in arena) + 1 < 28: bad.append("arena smaller than 30 x 28")
    cl = camps()
    if sum(c[1] for c in cl) != 18: bad.append("common monsters total %d, BIBLE says 18" % sum(c[1] for c in cl))
    for typ, cnt, tx, ty, w, h in cl:
        tiles = [(x, y) for y in range(ty, ty + h) for x in range(tx, tx + w)]
        if any(rows[y][x] in SOLID for x, y in tiles): bad.append("camp %s rect has solid tiles" % typ)
        if len(tiles) < 2 * cnt: bad.append("camp %s too small" % typ)
        for px, py in (START, (6, 33)):
            d = min(math.hypot(x - px, y - py) for x, y in tiles)
            if d < 5: bad.append("camp %s only %.1f tiles from the entrance" % (typ, d))
    print("shrine", "OK" if not bad else "PROBLEMS", "(%d walkable, %d reachable, %d camp entries)" % (len(free), len(reach & free), len(cl)))
    for b in bad: print("  PROBLEM", b)
    return not bad


def paint(rows, path, scale, labels):
    im = Image.new("RGB", (W * scale, H * scale)); d = ImageDraw.Draw(im)
    for y in range(H):
        for x in range(W): d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=COL[rows[y][x]])
    if labels:
        for typ, cnt, tx, ty, w, h in camps():
            d.rectangle([tx * scale, ty * scale, (tx + w) * scale - 1, (ty + h) * scale - 1], outline=(255, 140, 0), width=2)
            d.text((tx * scale + 3, ty * scale + 3), "%s x%d" % (typ[3:], cnt), fill=(255, 255, 255))
        for nm, (tx, ty, *_r) in (("crystal 1", CRYSTAL_GATE), ("crystal 2", CRYSTAL_DEEP)):
            d.rectangle([tx * scale, ty * scale, (tx + 1) * scale - 1, (ty + 1) * scale - 1], fill=(112, 211, 196)); d.text((tx * scale + scale, ty * scale), nm, fill=(255, 255, 255))
        d.rectangle([AMBER[0] * scale, AMBER[1] * scale, (AMBER[2] + 1) * scale - 1, (AMBER[3] + 1) * scale - 1], fill=(228, 183, 106)); d.text(((AMBER[2] + 1) * scale, AMBER[1] * scale), "Memory Amber", fill=(255, 255, 255))
        d.ellipse([START[0] * scale, START[1] * scale, (START[0] + 1) * scale, (START[1] + 1) * scale], fill=(0, 200, 0)); d.text(((START[0] + 1) * scale, START[1] * scale), "start", fill=(255, 255, 255))
        d.ellipse([BOSS[0] * scale, BOSS[1] * scale, (BOSS[0] + 2) * scale, (BOSS[1] + 2) * scale], fill=(200, 40, 40)); d.text(((BOSS[0] + 2) * scale, BOSS[1] * scale), "Elder Root Guardian", fill=(255, 255, 255))
        for x in range(MOUTH[0], MOUTH[1] + 1): d.rectangle([x * scale, MOUTH[2] * scale, (x + 1) * scale - 1, (MOUTH[2] + 1) * scale - 1], outline=(60, 90, 255), width=2)
    im.save(path)


def main():
    rows = build()
    ok = check(rows)
    if "--check" in sys.argv: return 0 if ok else 1
    patch(os.path.join(MAPS, "TauAncientRootShrineMap.cs"), rows)
    os.makedirs(TILES, exist_ok=True); os.makedirs(SHOTS, exist_ok=True)
    paint(rows, os.path.join(TILES, "tau-ancient-root-shrine-ground.png"), PX, False)
    Image.new("RGB", (512, 512), COL["T"]).save(os.path.join(TILES, "tau-ancient-root-shrine-ground-border.png"))
    paint(rows, os.path.join(SHOTS, "phase06-layout-ancient-root-shrine.png"), 14, True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
