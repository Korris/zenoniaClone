"""
Writes Assets/Scripts/PaperArt.Borders.cs from Tools/ui-paper-sheets/paper-borders.json.

The cut tool (Tools/cut-ui-paper-sheet.py) keeps the 9-slice border of every Adventure Paper piece in that json
("<group>/<name>": [left, bottom, right, top], native pixels). The game reads borders from the C# table, so run this
after a `write` of the cut tool that added or changed a sliced piece:

    python Tools/export-ui-paper-borders-to-csharp.py

The json stays the one source: never edit PaperArt.Borders.cs by hand.

    python Tools/export-ui-paper-borders-to-csharp.py ro-soft

does the same for the RO Soft Fantasy kit: Tools/ui-ro-soft-sheets/ro-soft-borders.json -> Assets/Scripts/RoSoftSprites.Borders.cs.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETS = {  # set -> (border json, generated C# file, class, what the pieces are)
    "paper": ("Tools/ui-paper-sheets/paper-borders.json", "Assets/Scripts/PaperArt.Borders.cs", "PaperArt", "paper pieces"),
    "ro-soft": ("Tools/ui-ro-soft-sheets/ro-soft-borders.json", "Assets/Scripts/RoSoftSprites.Borders.cs", "RoSoftSprites", "RO Soft Fantasy kit pieces"),
}

HEADER = """using System.Collections.Generic;
using UnityEngine;

namespace ZenoniaProto
{
    /// <summary>
    /// 9-slice borders of the {what}, in native pixels (left, bottom, right, top); a piece not listed is drawn unsliced.
    /// GENERATED by Tools/export-ui-paper-borders-to-csharp.py from {source} (written by the cut tool):
    /// do not edit by hand, run the script again. A border with bottom = top = 0 is a horizontal-only piece: it scales with the
    /// widget height (PaperArt.Apply).
    /// </summary>
    public static partial class {cls}
    {{
        static readonly Dictionary<string, Vector4> Borders = new Dictionary<string, Vector4>
        {{
"""
FOOTER = """        };
    }
}
"""


def main(set_name):
    source, target, cls, what = SETS[set_name]
    with open(os.path.join(ROOT, source), encoding="utf-8") as f:
        borders = json.load(f)
    lines = []
    for name in sorted(borders):
        left, bottom, right, top = borders[name]
        lines.append('            {{ "{0}", new Vector4({1}f, {2}f, {3}f, {4}f) }},\n'.format(name, left, bottom, right, top))
    with open(os.path.join(ROOT, target), "w", encoding="utf-8", newline="\r\n") as f:
        header = HEADER.replace("{what}", what).replace("{source}", source).replace("{cls}", cls).replace("{{", "{")
        f.write(header + "".join(lines) + FOOTER)
    print("wrote", len(lines), "borders to", target)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "paper")
