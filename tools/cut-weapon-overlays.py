"""Cut weapon-overlay-sheet-raw.png (rows 1-3 = 9 [base, enhanced] pairs) into 18 upright PNGs,
manifest.json, src/data/weapon-overlay-manifest-generated.js and a contact sheet (incl. warrior hero)."""
from pathlib import Path
import json
import sys
import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
from weapon_overlay_geometry import (detect_grip, glow_hex, label_components, rotate_upright,
                                     split_columns, tilt_degrees, trim)

root = Path(__file__).resolve().parents[1]
out_dir = root / 'assets/custom/weapon-overlays'
ORDER = [['sword', 'sword2', 'rapier'], ['club', 'katana', 'axe'], ['lance', 'hammer', 'bigSword']]
# Fraction of weapon length up from the bottom for hafted weapons; swords use guard/pommel midpoint.
HAFT_GRIP = {'club': 0.20, 'axe': 0.25, 'lance': 0.30, 'hammer': 0.22}
MAX_H, PAD, HAZE, MIN_COMP, STRAIGHTEN = 256, 4, 48, 12, 2.0
SWORD_GAME_PX = 46  # approx baked-sword length (hilt-tip) in the 96px hero frame; contact-sheet scale only


def clean(img):
    a = np.array(img)
    a[..., 3] = np.where(a[..., 3] >= HAZE, a[..., 3], 0)
    return Image.fromarray(a, 'RGBA')


def cut_cell(sheet, band, x0, x1):
    """Keep all components >= MIN_COMP px (flame/lightning flecks included) inside the cell."""
    sub = sheet[band[0]:band[1], x0:x1].copy()
    keep = np.zeros(sub.shape[:2], bool)
    for ys, xs in label_components(sub[..., 3] > 0):
        if len(ys) >= MIN_COMP:
            keep[ys, xs] = True
    sub[~keep] = 0
    return Image.fromarray(sub, 'RGBA')


def main():
    sheet = np.array(Image.open(root / 'assets/custom/weapon-overlay-sheet-raw.png').convert('RGBA'))
    sheet[..., 3] = np.where(sheet[..., 3] >= HAZE, sheet[..., 3], 0)
    rows = np.nonzero((sheet[..., 3] > 0).any(axis=1))[0]
    bands = [(b[0], b[-1] + 1) for b in np.split(rows, np.where(np.diff(rows) > 8)[0] + 1)][:3]
    if len(bands) != 3:
        raise SystemExit(f'expected 3 weapon row bands, found {len(bands)}')
    pairs = {}
    for r, band in enumerate(bands):
        cols = split_columns(sheet[band[0]:band[1], :, 3], 6)
        for c, kind in enumerate(ORDER[r]):
            pairs[kind] = [cut_cell(sheet, band, *cols[c * 2]), cut_cell(sheet, band, *cols[c * 2 + 1])]
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest, scaled, src_h = {}, {}, {}
    for kind, (base, enh) in pairs.items():
        angle = tilt_degrees(np.array(base)[..., 3])
        print(f'{kind:9s} base tilt {angle:+.1f} deg')
        if kind == 'katana' and abs(angle) > STRAIGHTEN:  # only the katana genuinely leans
            base, enh = rotate_upright(base, angle), rotate_upright(enh, angle)
        base, enh = trim(clean(base), PAD), trim(clean(enh), PAD)
        src_h[kind] = base.height - 2 * PAD
        s = min(1.0, MAX_H / max(base.height, enh.height))  # same factor for the pair
        entry = {}
        for tag, im in (('base', base), ('enhanced', enh)):
            if s < 1:
                im = clean(im.resize((round(im.width * s), round(im.height * s)), Image.Resampling.LANCZOS))
            name = f'{kind}-{tag}.png'
            im.save(out_dir / name)
            gx, gy = detect_grip(im, HAFT_GRIP.get(kind))
            if np.array(im)[gy, gx, 3] == 0:
                raise SystemExit(f'{name}: grip ({gx},{gy}) is not on an opaque pixel')
            entry[tag] = {'file': name, 'w': im.width, 'h': im.height, 'gripX': gx, 'gripY': gy}
            scaled[(kind, tag)] = im
        entry['glow'] = glow_hex(enh)
        entry['length'] = round(src_h[kind] / src_h['sword'], 2) if 'sword' in src_h else 1.0
        manifest[kind] = entry
        print(f"{kind:9s} base {entry['base']['w']}x{entry['base']['h']} grip({entry['base']['gripX']},{entry['base']['gripY']}) "
              f"enh {entry['enhanced']['w']}x{entry['enhanced']['h']} grip({entry['enhanced']['gripX']},{entry['enhanced']['gripY']}) "
              f"glow {entry['glow']} length {entry['length']}")
    (out_dir / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    js = ('// GENERATED by tools/cut-weapon-overlays.py -- do not edit by hand.\n'
          '// Grip = pixel inside each PNG that sits in the hero hand; length = world length relative to sword.\n'
          f'export const WEAPON_OVERLAYS = Object.freeze({json.dumps(manifest, indent=2)});\n')
    (root / 'src/data/weapon-overlay-manifest-generated.js').write_text(js, encoding='utf-8')
    contact_sheet(manifest, scaled)


def crosshair(d, x, y, r):
    d.line([x - r, y, x + r, y], fill='#ff2bd6', width=2)
    d.line([x, y - r, x, y + r], fill='#ff2bd6', width=2)


def contact_sheet(manifest, scaled):
    """Top: all 18 at export size with grip crosshair. Bottom: beside the warrior hero at in-game scale (x3)."""
    cw, ch, bh, zoom = 260, 300, 330, 3
    top = ch * 3 + 30
    sheet = Image.new('RGB', (cw * 6, top + bh * 3), '#1c3143')
    d = ImageDraw.Draw(sheet)
    hero = Image.open(root / 'assets/hd/hero/normalized/idle.png').convert('RGBA').crop((0, 0, 96, 96))
    big_hero = hero.resize((96 * zoom, 96 * zoom), Image.Resampling.NEAREST)
    d.text((6, top - 18), f'In-game scale x{zoom}: hero 96px frame, sword={SWORD_GAME_PX}px (estimate); hero | base | enhanced; '
           'weapon placed beside hero at hand height, crosshair = grip', fill='#f0e3bf')
    for i, (kind, e) in enumerate(manifest.items()):
        for j, tag in enumerate(('base', 'enhanced')):
            ox, oy = (i % 3) * 2 * cw + j * cw, (i // 3) * ch
            im = scaled[(kind, tag)]
            px, py = ox + (cw - im.width) // 2, oy + 20
            sheet.paste(im, (px, py), im)
            crosshair(d, px + e[tag]['gripX'], py + e[tag]['gripY'], 9)
            d.text((ox + 6, oy + 4), f'{kind} {tag} grip({e[tag]["gripX"]},{e[tag]["gripY"]})', fill='#f0e3bf')
        ox, oy = (i % 3) * cw * 2, top + (i // 3) * bh
        sheet.paste(big_hero, (ox + 4, oy + 20), big_hero)
        s = SWORD_GAME_PX * e['length'] * zoom / (scaled[(kind, 'base')].height - 8)  # same scale for the pair
        for j, tag in enumerate(('base', 'enhanced')):
            im = scaled[(kind, tag)]
            im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.Resampling.LANCZOS)
            hx, hy = ox + 96 * zoom + 50 + j * 100, oy + 20 + 62 * zoom
            sheet.paste(im, (hx - round(e[tag]['gripX'] * s), hy - round(e[tag]['gripY'] * s)), im)
            crosshair(d, hx, hy, 6)
        d.text((ox + 4, oy + 4), kind, fill='#f0e3bf')
    sheet.save(out_dir / 'contact-sheet.png')
    print('Wrote 18 overlays, manifest.json, generated module, contact-sheet.png')


main()
