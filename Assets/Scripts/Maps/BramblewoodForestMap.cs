            "TTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTT",
            "TTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTTT",
        };

        static readonly Vector2Int PlayerStartTile = new Vector2Int(17, 3);

        /// <summary>
        /// Top road (two tiles wide at row 0): to Willowbrook Meadows, landing on its south trail two tiles above its gate pair (46,44)/(47,44). West cave mouth (2,13): into Rootburrow, landing
        /// three tiles inside its lit entrance crack. No gates: every portal is always open (World Map 2.0 rule).
        /// </summary>
        static readonly MapPortal[] PortalList =
        {
            new MapPortal(17, 0, WillowbrookMeadowsMap.MapId, 47, 42), new MapPortal(18, 0, WillowbrookMeadowsMap.MapId, 47, 42),
            new MapPortal(2, 13, RootburrowMap.MapId, 32, 13),
        };

        public BramblewoodForestMap() : base(Rows, "Tw")
        {
            foreach (MapProp p in BramblewoodForestProps.All)
            {
                PropDef d;
                if (VillagePropDefs.TryGet(p.Type, out d)) BlockTiles(p.Tx, p.Ty - d.FootH + 1, d.FootW, d.FootH);
                else Debug.LogError("[ZenoniaProto] unknown village prop " + p.Type);
            }
        }

        public override string Id { get { return MapId; } }
        public override string Name { get { return "Bramblewood Forest"; } }
        public override string GroundTexture { get { return "Sprites/village/tiles/bramblewood-forest-ground"; } }
        public override string Music { get { return "frost-hollow"; } } // no track of its own yet
        public override bool Hostile { get { return true; } }
        public override Vector2 PlayerStart { get { return FrostHollowMap.TileFeet(PlayerStartTile.x, PlayerStartTile.y, 2f); } }
        public override MapPortal[] Portals { get { return PortalList; } }
        public override MapProp[] Props { get { return BramblewoodForestProps.All; } }
    }
}
