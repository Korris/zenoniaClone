{
    /// <summary>
    /// Bramblewood Forest (World Map 2.1, 13/11/2026): the Lv6-10 hunting wood south of Willowbrook Meadows, 36x24, ONE painted ground (Sprites/village/tiles/bramblewood-forest-ground.png, the
    /// ChatGPT "ground only" painting: roads, stream, waterfall cliff, bridge, root cave and the dense forest ring) with the bw* props y-sorted on top (BramblewoodForestProps).
    /// Rows: T forest ring / trunks / cliff / HUD rows 21-23 (solid)  g grass  d road  B bridge  w stream (solid). Three clearings hold the monsters (MapSpawnTable): north-west (mantis, wolves),
    /// north-east across the bridge (wolves, treants) and the big south one (treants, sprites, and Thornfang Alpha, the map boss). Exits: the road at the top (Willowbrook's south trail) and
    /// the root cave on the west edge (Rootburrow). The painted road also runs off the EAST edge, but World Map 2.1 has no map there yet: cols 34-35 are solid and brambles cover the road end.
    /// </summary>
    public sealed class BramblewoodForestMap : TileMapBase
    {
        public const string MapId = "bramblewoodForest";

        // Generated by Tools/build-bramblewood-rootburrow-rows.py from plans/261113-1010-world-map-new-maps/layout/bramblewood-forest-rows-hand.txt (edit that file, not these rows).
        static readonly string[] Rows =
        {
            "TTTTTTTTTTTTTTTTTddTTTTTTTTTTTTTTTTT",
            "TTTTTTTTTTTTTTTTgddgTTTTTTTTTTTTTTTT",
            "TTTTTTTTTTTTTggggddgTTTTTTTTTTTTTTTT",
            "TTTTTTgggggggggggddggggggwwTTTTTTTTT",
            "TTTTTgggggggggggggggggggwwwTTTTTTTTT",
            "TTTTTTggggggggggggggggwwwwggggTTTTTT",
            "TTTTTggggggggggggggggwwwgggggggggTTT",
            "TTTTggggggggggggggggwwwggggggggggTTT",
            "TTTTggggggggggggggggwwgggggggggggTTT",
            "TTTTTgggggggggggggggwwwgggggggggggTT",
            "TTTTTggggggggggggggwwwwgggggggggggTT",
            "TTTTTTgggggggggggggwwwggggggggggggTT",
            "TTTTTTTddddddddddddBBBddddddddddddTT",
            "TTdddddddddddddddddBBBddddddddddddTT",
            "TTTdddddgggggggwwwwwwwggggggggggggTT",
