    /// <summary>
    /// Rootburrow: the Lv6-12 cave under Bramblewood Forest (World Map 2.1, 13/11/2026). Since 21/11/2026 (V3) a dark violet 2.5D cave laid out to DELVE
    /// DEEPER like an RO3 dungeon (user: "map dungeon thì làm kiểu map đi vào sâu ấy chứ không dàn trải ra như map thường"), 60 x 24, from the east edge
    /// (Bramblewood's cave) westward: entrance -> narrow tunnel -> monster cave I (Lv6-7) -> winding tunnel -> monster cave II (Lv8-10) -> deep tunnel ->
    /// the Ambercap Warden's cave (map boss, MapSpawnTable.BossFor) -> last tunnel -> the Wanted arena (17 x 17, Aetherglyph Owl on its days, WantedBoss)
    /// with the arch to Thornheart Chamber at its north-west. Rows from Tools/build-rootburrow-delve-rows.py (T solid, d floor); ground from two violet
    /// swatches (Tools/build-map-25d-dungeon-ground.py, 2 chunks); every standing wall / crystal / rune orb is a prop on a solid tile (RootburrowProps), the
    /// lights come from them (DungeonLights), darker the deeper you go (View25DProfile.DarkDungeon). docs/reference/rootburrow-dark-25d/,
    /// plans/261121-1145-dark-dungeon-boss/plan.md. A normal shared map (no instances yet).
    /// </summary>
    public sealed class RootburrowMap : TileMapBase
    {
        public const string MapId = "rootburrow";
        /// <summary>Arrival from Bramblewood's cave (two tiles inside the east gate) and from Thornheart's corridor (two tiles below the arch).</summary>
        public const int EntranceArrivalTx = 56, EntranceArrivalTy = 12, ArchArrivalTx = 4, ArchArrivalTy = 4;

