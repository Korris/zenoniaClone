        static readonly Vector2Int PlayerStartTile = new Vector2Int(EntranceArrivalTx, EntranceArrivalTy);

        /// <summary>East gate (59, 11-13): back to Bramblewood Forest, two tiles out of its cave mouth. North-west arch of the arena (4,2)/(5,2): into Thornheart Chamber, just above its corridor mouth. Always open.</summary>
        static readonly MapPortal[] PortalList =
        {
            new MapPortal(59, 11, BramblewoodForestMap.MapId, 4, 13), new MapPortal(59, 12, BramblewoodForestMap.MapId, 4, 13), new MapPortal(59, 13, BramblewoodForestMap.MapId, 4, 13),
            new MapPortal(4, 2, ThornheartChamberMap.MapId, 11, 9), new MapPortal(5, 2, ThornheartChamberMap.MapId, 12, 9),
        };

        public RootburrowMap() : base(Rows, "Tw")
        {
            foreach (MapProp p in RootburrowProps.All)
            {
                PropDef d;
                if (VillagePropDefs.TryGet(p.Type, out d)) BlockTiles(p.Tx, p.Ty - d.FootH + 1, d.FootW, d.FootH);
                else Debug.LogError("[ZenoniaProto] unknown village prop " + p.Type);
            }
        }

        public override string Id { get { return MapId; } }
        public override string Name { get { return "Rootburrow"; } }
        public override string GroundTexture { get { return "Sprites/village/tiles/rootburrow-ground"; } }
        public override int GroundChunkCols { get { return 2; } } // 3840 px wide: two 1920 x 1536 chunks (Android imports at most 2048)
        public override string Music { get { return "frost-hollow"; } } // no track of its own yet
        public override bool Hostile { get { return true; } }
        public override Vector2 PlayerStart { get { return FrostHollowMap.TileFeet(PlayerStartTile.x, PlayerStartTile.y, 2f); } }
        public override MapPortal[] Portals { get { return PortalList; } }
        public override MapProp[] Props { get { return RootburrowProps.All; } }
    }
